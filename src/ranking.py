def bubble_sort(items: list) -> list:
    """Sort by repeatedly swapping adjacent out-of-order pairs."""
    arr = items.copy()
    n = len(arr)
    for i in range(n):
        swapped = False
        for j in range(n - 1 - i):
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swapped = True
        if not swapped:
            break
    return arr
